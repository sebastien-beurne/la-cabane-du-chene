export const themeById = key => {const id=THEMES[key]?key:DEFAULT_THEME;return {...THEMES[id],id};};
export function themeVariables(key){const t=themeById(key),c=t.colors;return {...Object.fromEntries(Object.entries(c).map(([k,v])=>['--theme-'+k,v])),'--font-display':t.font,'--theme-display':t.font,'--radius':t.radius,'--theme-accent':c.action,'--theme-paper':c.paper,'--theme-forest':c.brand};}
export function applyTheme(key){const t=themeById(key),node=document.documentElement,c=t.colors;for(const[k,v]of Object.entries(themeVariables(key)))node.style.setProperty(k,v);
 const map={primary:'brand',ring:'brand',background:'paper',foreground:'ink',card:'paper','card-foreground':'ink',popover:'paper','popover-foreground':'ink',secondary:'canvas','secondary-foreground':'ink',accent:'action',border:'canvas',input:'canvas',muted:'canvas','muted-foreground':'muted-ink'};
 for(const[k,v]of Object.entries(map))node.style.setProperty('--'+k,toHsl(c[v]));
 node.style.setProperty('--primary-foreground','0 0% 100%');node.style.setProperty('--accent-foreground','0 0% 100%');node.dataset.theme=t.id;node.dataset.siteTheme=t.id;
}
function toHsl(rgb){const [r,g,b]=rgb.split(' ').map(Number).map(x=>x/255),max=Math.max(r,g,b),min=Math.min(r,g,b),d=max-min,l=(max+min)/2;let h=0,s=0;if(d){s=d/(1-Math.abs(2*l-1));h=max===r?((g-b)/d)%6:max===g?(b-r)/d+2:(r-g)/d+4;h*=60;if(h<0)h+=360;}return `${h.toFixed(1)} ${(s*100).toFixed(1)}% ${(l*100).toFixed(1)}%`;}
